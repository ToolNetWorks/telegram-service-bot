SERVICES_BY_ID: dict[int, ServiceDefinition] = {s.id: s for s in SERVICES}


# Helper functions

def platforms_all() -> list[PlatformDefinition]:
    return [p for p in PLATFORMS if p.enabled and p.visible]


def platform_by_slug(slug: str) -> PlatformDefinition | None:
    for p in PLATFORMS:
        if p.slug == slug and p.enabled and p.visible:
            return p
    return None


def categories_for_platform(platform_id: int) -> list[CategoryDefinition]:
    """Return all visible categories for a platform, including Coming Soon."""
    return [c for c in CATEGORIES if c.platform_id == platform_id and c.visible]


def category_by_id(category_id: int) -> CategoryDefinition | None:
    for c in CATEGORIES:
        if c.id == category_id:
            return c
    return None


def services_for_category(category_id: int) -> list[ServiceDefinition]:
    return [s for s in SERVICES if s.category_id == category_id]


def service_by_id(service_id: int) -> ServiceDefinition | None:
    for s in SERVICES:
        if s.id == service_id:
            return s
    return None


def service_by_provider_id(provider_id: str, provider_service_id: str) -> ServiceDefinition | None:
    for s in SERVICES:
        if s.provider_id == provider_id and s.provider_service_id == provider_service_id:
            return s
    return None
